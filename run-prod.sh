#!/bin/bash

# 에러 발생 시 즉시 중단
set -e

# backend 디렉터리로 이동
cd "$(dirname "$0")/backend"

echo "============================================="
echo "🔄 AIPod 서비스 최신 빌드 다운로드 및 실행을 시작합니다..."
echo "============================================="

# 최신 이미지를 받아오고(pull always) 컨테이너 재실행
docker compose -f docker-compose.prod.yml up -d --pull always

echo "============================================="
echo "✅ AIPod 모든 서비스가 정상적으로 실행되었습니다!"
echo "============================================="
